import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createClient } from '@supabase/supabase-js';

process.env.TZ='America/New_York';
const playwrightPath=process.env.SCHEDULE_PLAYWRIGHT_PATH;
if(!playwrightPath) throw new Error('Set SCHEDULE_PLAYWRIGHT_PATH.');
const {chromium}=await import(playwrightPath);
const appUrl=process.env.SCHEDULE_APP_URL ?? 'http://127.0.0.1:3007';
const isLocal=url=>['localhost','127.0.0.1','::1','[::1]'].includes(new URL(url).hostname);
assert(isLocal(appUrl),'UI smoke test must be local');
const raw=execFileSync('./node_modules/.bin/supabase',['status','--network-id','pilotseal-local','--output','env'],{encoding:'utf8'});
const env=Object.fromEntries(raw.split(/\r?\n/).flatMap(line=>{const match=line.match(/^([A-Z0-9_]+)=["']?(.*?)["']?$/);return match?[[match[1],match[2]]]:[];}));
assert(isLocal(env.API_URL),'Supabase target must be local');
const options={auth:{persistSession:false,autoRefreshToken:false}};
const admin=createClient(env.API_URL,env.SERVICE_ROLE_KEY ?? env.SECRET_KEY,options);
const cfi=createClient(env.API_URL,env.ANON_KEY ?? env.PUBLISHABLE_KEY,options);
const unwrap=({data,error})=>{if(error) throw new Error(error.message);return data;};
const auth=unwrap(await cfi.auth.signInWithPassword({email:'pilot.one@example.test',password:'LocalPilot!2026'}));
const cfiId=auth.user.id;
const studentId=unwrap(await admin.from('profiles').select('id').eq('email','instructor.one@example.test').single()).id;
const personId='55000000-0000-4000-8000-000000000001';
const selfId='55000000-0000-4000-8000-000000000002';
const certId='55000000-0000-4000-8000-000000000003';
const aircraftId='30000000-0000-4000-8000-000000000001';
const note=`Aircraft UI ${Date.now()}`;
const priorProfile=unwrap(await admin.from('profiles').select('self_person_id').eq('id',cfiId).single());
const priorPrefs=unwrap(await admin.from('dashboard_preferences').select('*').eq('user_id',cfiId).maybeSingle());
const priorMx=unwrap(await admin.from('organization_aircraft_maintenance').select('*').eq('aircraft_id',aircraftId).maybeSingle());
const day=new Date();day.setDate(day.getDate()+8);day.setHours(12,0,0,0);
const date=[day.getFullYear(),String(day.getMonth()+1).padStart(2,'0'),String(day.getDate()).padStart(2,'0')].join('-');
const browser=await chromium.launch({headless:true,channel:'chrome'});
try{
  if(!priorProfile.self_person_id){unwrap(await admin.from('saved_people').insert({id:selfId,user_id:cfiId,role:'self',display_name:'Aircraft UI CFI'}));unwrap(await admin.from('profiles').update({self_person_id:selfId}).eq('id',cfiId));}
  const actualSelf=priorProfile.self_person_id ?? selfId;
  unwrap(await admin.from('saved_person_certificates').upsert({id:certId,user_id:cfiId,person_id:actualSelf,certificate_type:'flight_instructor',certificate_number:'UI-AIR-CFI',ratings:['ASEL'],last_event_date:date}));
  unwrap(await admin.from('saved_people').upsert({id:personId,user_id:cfiId,role:'student',display_name:'Aircraft UI Student',cert_number:'UI-AIR-1'}));
  unwrap(await admin.from('saved_person_account_links').upsert({saved_person_id:personId,owner_user_id:cfiId,linked_user_id:studentId}));
  unwrap(await admin.from('cfi_schedule_student_grants').upsert({cfi_user_id:cfiId,saved_person_id:personId,student_user_id:studentId,access_enabled:true}));
  unwrap(await admin.from('dashboard_preferences').upsert({user_id:cfiId,enabled_feature_ids:['cfi_schedule']}));
  unwrap(await admin.from('organization_aircraft_maintenance').upsert({aircraft_id:aircraftId,operational_status:'grounded',operational_status_note:'Synthetic UI status',updated_by:cfiId}));
  const context=await browser.newContext({viewport:{width:390,height:900},timezoneId:'America/New_York'});
  await context.route('**/*',route=>isLocal(route.request().url())?route.continue():route.abort());
  const key=`sb-${new URL(env.API_URL).hostname.split('.')[0]}-auth-token`;
  await context.addInitScript(({key,value})=>localStorage.setItem(key,value),{key,value:JSON.stringify(auth.session)});
  const page=await context.newPage();
  await page.goto(`${appUrl}/dashboard/schedule`);
  await page.getByLabel('Schedule workspace',{exact:true}).waitFor();
  await page.getByLabel('Jump to date').fill(date);
  await page.locator('[aria-label="Week schedule"][aria-busy="false"]').waitFor();
  await page.getByRole('button',{name:'Add to schedule',exact:true}).click();
  await page.getByRole('menuitem',{name:'Add lesson',exact:true}).click();
  const lesson=page.getByRole('dialog',{name:'Add lesson',exact:true});
  await lesson.waitFor();
  await lesson.getByLabel('Date',{exact:true}).fill(date);
  const aircraftSelect=lesson.locator('select').nth(3);
  await aircraftSelect.selectOption(aircraftId);
  assert.match(await aircraftSelect.locator('option:checked').textContent(),/N000PS.*grounded/i);
  await lesson.getByLabel('Note',{exact:true}).fill(note);
  await lesson.getByRole('button',{name:'Save lesson',exact:true}).click();
  await lesson.getByText(/currently grounded/i).first().waitFor();
  await lesson.getByRole('button',{name:'Save anyway',exact:true}).click();
  await lesson.waitFor({state:'hidden'});
  assert.equal(unwrap(await admin.from('cfi_schedule_events').select('aircraft_id').eq('note',note).single()).aircraft_id,aircraftId,'manual Flight saves its aircraft');
  assert.equal(await page.getByText(/Unpublished draft/).count(),0,'manual lesson saves directly without a second publish step');
  await page.getByRole('button',{name:'Add to schedule',exact:true}).click();
  await page.getByRole('menuitem',{name:'Auto schedule',exact:true}).click();
  const auto=page.getByRole('dialog',{name:'Automatic scheduling',exact:true});
  assert(await auto.getByRole('checkbox',{name:/N000PS/}).isChecked(),'available aircraft are selected for the run');
  assert.equal(await auto.getByLabel('Flight lessons for Aircraft UI Student').count(),1);
  assert.equal(await auto.getByLabel('Ground lessons for Aircraft UI Student').count(),1);
  await context.close();
  console.log('Aircraft schedule UI smoke assertions passed.');
} finally {
  await admin.from('cfi_schedule_events').delete().eq('note',note);
  await admin.from('cfi_schedule_student_grants').delete().eq('saved_person_id',personId);
  await admin.from('saved_person_account_links').delete().eq('saved_person_id',personId);
  await admin.from('saved_people').delete().eq('id',personId);
  await admin.from('saved_person_certificates').delete().eq('id',certId);
  if(!priorProfile.self_person_id){await admin.from('profiles').update({self_person_id:null}).eq('id',cfiId);await admin.from('saved_people').delete().eq('id',selfId);}
  if(priorPrefs) await admin.from('dashboard_preferences').upsert(priorPrefs); else await admin.from('dashboard_preferences').delete().eq('user_id',cfiId);
  if(priorMx) await admin.from('organization_aircraft_maintenance').upsert(priorMx); else await admin.from('organization_aircraft_maintenance').delete().eq('aircraft_id',aircraftId);
  await browser.close();
}
